# operands

CONDS = {"eq": "zf", "ne": "!zf", "hs": "cf", "cs": "cf", "lo": "!cf", "cc": "!cf", "mi": "nf", "pl": "!nf",
         "vs": "vf", "vc": "!vf", "hi": "(cf && !zf)", "ls": "(!cf || zf)", "ge": "(nf == vf)",
         "lt": "(nf != vf)", "gt": "(!zf && nf == vf)", "le": "(zf || nf != vf)", "al": "1", "nv": "1"}
INVERT = {"eq": "ne", "ne": "eq", "hs": "lo", "cs": "lo", "lo": "hs", "cc": "hs", "mi": "pl", "pl": "mi",
          "vs": "vc", "vc": "vs", "hi": "ls", "ls": "hi", "ge": "lt", "lt": "ge", "gt": "le", "le": "gt"}
FLD = {8: "b", 16: "h", 32: "w", 64: "q"}
SFLD = {8: "sb", 16: "sh", 32: "sw", 64: "sq"}
FFLD = {32: "f", 64: "d"}
UT = {8: "uint8_t", 16: "uint16_t", 32: "uint32_t", 64: "uint64_t"}
ST = {8: "int8_t", 16: "int16_t", 32: "int32_t", 64: "int64_t"}
FT = {32: "float", 64: "double"}
ESZ = {"b": 8, "h": 16, "s": 32, "d": 64, "q": 128}


class Op:
    def __init__(self, kind, **kw):
        self.kind = kind
        self.__dict__.update(kw)

    def __repr__(self):
        return "Op(%s)" % ", ".join("%s=%r" % kv for kv in self.__dict__.items())


def split_ops(s):
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch in "[{":
            depth += 1
        elif ch in "]}":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip()); cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def parse_imm(t):
    t = t.lstrip("#")
    if re.fullmatch(r"-?0x[0-9a-fA-F]+", t):
        return int(t, 16)
    if re.fullmatch(r"-?\d+", t):
        return int(t, 10) if not (len(t) > 1 and t.startswith("0") and set(t) == {"0"}) else 0
    return float(t)


def parse_reg(t):
    m = re.fullmatch(r"([xw])(\d+)", t)
    if m:
        return Op("g", n=int(m.group(2)), w=64 if m.group(1) == "x" else 32)
    if t in ("sp", "wsp"):
        return Op("sp", w=64 if t == "sp" else 32)
    if t in ("xzr", "wzr"):
        return Op("zr", w=64 if t == "xzr" else 32)
    if t == "fp":
        return Op("g", n=29, w=64)
    if t == "lr":
        return Op("g", n=30, w=64)
    m = re.fullmatch(r"([bhsdq])(\d+)", t)
    if m:
        return Op("fs", n=int(m.group(2)), w=ESZ[m.group(1)])
    m = re.fullmatch(r"v(\d+)\.(\d*)([bhsd])\[(0x[0-9a-f]+|\d+)\]", t)
    if m:
        return Op("ve", n=int(m.group(1)), es=ESZ[m.group(3)], idx=int(m.group(4), 0))
    m = re.fullmatch(r"v(\d+)\.(\d+)([bhsd])", t)
    if m:
        return Op("v", n=int(m.group(1)), cnt=int(m.group(2)), es=ESZ[m.group(3)])
    m = re.fullmatch(r"v(\d+)\.1q", t)
    if m:
        return Op("v", n=int(m.group(1)), cnt=1, es=128)
    return None


def parse_op(t):
    r = parse_reg(t)
    if r:
        return r
    if t.startswith("#"):
        return Op("imm", v=parse_imm(t))
    if t.startswith("["):
        pre = t.endswith("!")
        inner = t.rstrip("!")[1:-1]
        parts = [p.strip() for p in inner.split(",")]
        base = parse_reg(parts[0])
        o = Op("mem", base=base, index=None, ext=None, shift=0, disp=0, pre=pre)
        if len(parts) >= 2:
            if parts[1].startswith("#"):
                o.disp = parse_imm(parts[1])
            else:
                o.index = parse_reg(parts[1])
                if len(parts) >= 3:
                    m = re.fullmatch(r"(\w+)(?:\s+#(\d+))?", parts[2])
                    o.ext, o.shift = m.group(1), int(m.group(2) or 0)
        return o
    if t.startswith("{"):
        m = re.fullmatch(r"\{(.*)\}(?:\[(\d+)\])?", t)
        regs = [x.strip() for x in m.group(1).split(",")]
        if len(regs) == 1 and " - " in regs[0]:
            a, b = [x.strip() for x in regs[0].split(" - ")]
            ra, rb = parse_reg(a if "." in a else a), parse_reg(b)
            suffix = a[a.index("."):]
            regs = ["v%d%s" % (k % 32, suffix) for k in range(ra.n, ra.n + ((rb.n - ra.n) % 32) + 1)]
        idx = m.group(2)
        ops = []
        for x in regs:
            if idx is not None:
                mm = re.fullmatch(r"v(\d+)\.([bhsd])", x)
                ops.append(Op("ve", n=int(mm.group(1)), es=ESZ[mm.group(2)], idx=int(idx)))
            else:
                ops.append(parse_reg(x))
        return Op("list", regs=ops)
    m = re.fullmatch(r"(lsl|lsr|asr|ror|msl)\s+#(\d+)", t)
    if m:
        return Op("shift", t=m.group(1), amt=int(m.group(2)))
    m = re.fullmatch(r"([us]xt[bhwx])(?:\s+#(\d+))?", t)
    if m:
        return Op("ext", t=m.group(1), amt=int(m.group(2) or 0))
    if t in CONDS:
        return Op("cond", c=t)
    return Op("sym", name=t)


class Unsupported(Exception):
    pass


