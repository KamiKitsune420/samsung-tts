class Translator:
    def __init__(self, images, host=(), overrides=(), stubs=(), stub_pred=None, wraps=()):
        self.wraps = set(wraps)             # symbols whose callers get H_<name>, the original staying as O_<name>
        self.stub_pred = stub_pred          # (image, address, name) -> True to replace the function by a trap
        self.stubs = set(stubs)             # (image, address) of functions replaced by a trap
        self.images = images
        self.host = set(host)               # symbols always bound to the host
        self.overrides = set(overrides)     # internal symbols replaced by a host function
        self.host_used = set()
        self.done = {}                      # (image, addr) -> C text
        self.problems = []
        self.unresolved_list = []
        self.jt_failures = []
        self.unresolved_br = 0              # functions with a computed jump that was not understood

    def call_symbol(self, fn, name):
        if name in self.overrides or name in self.host:
            self.host_used.add(name)
            return "H_%s(c);" % cname(name)
        for img in ([fn.img] + [i for i in self.images.values() if i is not fn.img]):
            a = img.exports.get(name)
            if a is not None and a in img.funcs:
                fn.callees.add((img.index, a))
                return "F_%d_%x(c);" % (img.index, a)
        self.host_used.add(name)
        return "H_%s(c);" % cname(name)

    def run(self, roots):
        work = list(roots)
        while work:
            key = work.pop()
            if key in self.done:
                continue
            img = self.images[key[0]]
            size = img.funcs.get(key[1])
            if size is None:
                self.problems.append((key, "not a function start"))
                self.done[key] = "void F_%d_%x(cpu_t *c) { a2c_trap(c, 0x%xULL, \"not a function start\"); }\n" % (key[0], key[1], key[1])
                continue
            if img.byaddr.get(key[1]) in self.overrides:
                pass        # replaced by a host function below, whatever the stub rules say
            elif key in self.stubs or (self.stub_pred and self.stub_pred(img, key[1], img.byaddr.get(key[1]))):
                self.stubbed = getattr(self, "stubbed", 0) + 1
                self.done[key] = "void F_%d_%x(cpu_t *c) { a2c_trap(c, 0x%xULL, \"stubbed out\"); }\n" % (key[0], key[1], key[1])
                continue
            # an exported symbol may be replaced by a host function
            name = img.byaddr.get(key[1])
            if name in self.overrides:
                self.host_used.add(name)
                self.done[key] = "void F_%d_%x(cpu_t *c) { H_%s(c); }\n" % (key[0], key[1], cname(name))
                continue
            f = Func(self, img, key[1], size)
            self.done[key] = f.translate()
            if name in self.wraps:
                # a faster host version stands in front; it may call the translation, O_<name>, for the cases
                # it does not handle
                me = "F_%d_%x" % key
                self.done[key] = (self.done[key].replace("void %s(cpu_t *c) {" % me, "void O_%s(cpu_t *c) {" % cname(name), 1)
                                  + "void H_%s(cpu_t *c);" % cname(name) + chr(10)
                                  + "void %s(cpu_t *c) { H_%s(c); }" % (me, cname(name)) + chr(10))
            for u in f.unsupported:
                self.problems.append((key, u))
            work.extend(f.callees)

    def write(self, path, profile=False):
        """profile=True wraps every function in a tick counter (a2c_prof_*), for finding where time goes."""
        keys = sorted(self.done)
        with open(path, "w", encoding="utf8", newline="\n") as out:
            out.write('#include "a2c_rt.h"\n\n')
            for n in sorted(self.host_used):
                out.write("void H_%s(cpu_t *c);\n" % cname(n))
            for k in keys:
                out.write("void F_%d_%x(cpu_t *c);\n" % k)
            out.write("\n")
            if profile:
                out.write("#include <x86intrin.h>\nuint64_t a2c_prof_ticks[%d], a2c_prof_calls[%d];\n" % (len(keys), len(keys)))
                out.write("const char *const a2c_prof_names[] = { %s };\nconst int a2c_prof_n = %d;\n"
                          % (", ".join('"%s"' % (self.images[k[0]].byaddr.get(k[1]) or "F_%d_%x" % k) for k in keys), len(keys)))
            for n, k in enumerate(keys):
                img = self.images[k[0]]
                out.write("/* %s */\n" % img.byaddr.get(k[1], "(local)"))
                text = self.done[k]
                if profile:
                    name = "F_%d_%x" % k
                    text = text.replace("void %s(cpu_t *c) {" % name, "static void I%s(cpu_t *c) {" % name, 1)
                    text += ("void %s(cpu_t *c) { uint64_t t_ = __rdtsc(); I%s(c); a2c_prof_ticks[%d] += __rdtsc() - t_; "
                             "a2c_prof_calls[%d]++; }\n" % (name, name, n, n))
                out.write(text)
                out.write("\n")
            out.write("const a2c_func a2c_funcs[] = {\n")
            for k in keys:
                out.write("  { IMG%d + 0x%xULL, F_%d_%x },\n" % (k[0], k[1], k[0], k[1]))
            out.write("};\nconst int a2c_nfuncs = %d;\n" % len(keys))
            out.write("const a2c_export a2c_exports[] = {\n")
            for k in keys:
                name = self.images[k[0]].byaddr.get(k[1])
                if name:
                    out.write("  { \"%s\", F_%d_%x },\n" % (name, k[0], k[1]))
            out.write("  { 0, 0 }\n};\n")
            out.write("const char *const a2c_host_names[] = { %s 0 };\n" % " ".join('"%s",' % n for n in sorted(self.host_used)))
            out.write("void (*const a2c_host_funcs[])(cpu_t *) = { %s 0 };\n" % " ".join("H_%s," % cname(n) for n in sorted(self.host_used)))

    def write_split(self, outdir, parts):
        """The same as write(), as gen_decl.h, gen_000.c ... and gen_tables.c in outdir, the functions spread over
        `parts` files of about equal size so they can be compiled in parallel. Returns the file names."""
        import os
        os.makedirs(outdir, exist_ok=True)
        keys = sorted(self.done)
        with _KeepIfSame(os.path.join(outdir, "gen_decl.h")) as out:
            out.write('#include "a2c_rt.h"\n')
            for n in sorted(self.host_used):
                out.write("void H_%s(cpu_t *c);\n" % cname(n))
            for k in keys:
                out.write("void F_%d_%x(cpu_t *c);\n" % k)
        total = sum(len(self.done[k]) for k in keys)
        names, part, size, out = [], 0, 0, None
        for k in keys:
            if out is None or (size > total / parts and part < parts):
                if out:
                    out.close()
                name = "gen_%03d.c" % part
                names.append(name)
                out = _KeepIfSame(os.path.join(outdir, name))
                out.write('#include "gen_decl.h"\n\n')
                part += 1; size = 0
            out.write("/* %s */\n" % self.images[k[0]].byaddr.get(k[1], "(local)"))
            out.write(self.done[k]); out.write("\n")
            size += len(self.done[k])
        if out:
            out.close()
        with _KeepIfSame(os.path.join(outdir, "gen_tables.c")) as out:
            out.write('#include "gen_decl.h"\n\n')
            out.write("const a2c_func a2c_funcs[] = {\n")
            for k in keys:
                out.write("  { IMG%d + 0x%xULL, F_%d_%x },\n" % (k[0], k[1], k[0], k[1]))
            out.write("};\nconst int a2c_nfuncs = %d;\n" % len(keys))
            out.write("const a2c_export a2c_exports[] = {\n")
            for k in keys:
                name = self.images[k[0]].byaddr.get(k[1])
                if name:
                    out.write("  { \"%s\", F_%d_%x },\n" % (name, k[0], k[1]))
            out.write("  { 0, 0 }\n};\n")
            out.write("const char *const a2c_host_names[] = { %s 0 };\n" % " ".join('"%s",' % n for n in sorted(self.host_used)))
            out.write("void (*const a2c_host_funcs[])(cpu_t *) = { %s 0 };\n" % " ".join("H_%s," % cname(n) for n in sorted(self.host_used)))
        names.append("gen_tables.c")
        return names


class _KeepIfSame:
    """A text file that is only rewritten if its content changed, so its timestamp tells a build what to redo."""
    def __init__(self, path):
        self.path, self.parts = path, []

    def write(self, s):
        self.parts.append(s)

    def close(self):
        import os
        text = "".join(self.parts).encode("utf8")
        if os.path.exists(self.path):
            with open(self.path, "rb") as f:
                if f.read() == text:
                    return
        with open(self.path, "wb") as f:
            f.write(text)

    def __enter__(self):
        return self

    def __exit__(self, *a):
        self.close()


def cname(n):
    return re.sub(r"[^A-Za-z0-9_]", "_", n)
