"""a2c: translate arm64 machine code from ELF shared libraries into C, one C function per original function.

The generated C keeps the original's memory layout (the library is mapped at run time and pointers are real
pointers), so results are the original's bit for bit as long as each instruction is translated faithfully.
Nothing generated by this tool belongs in the repository: it is a derivative of the library it was run on.

Model (see a2c_rt.h):
  - every function is `void F_<image>_<address>(cpu_t *c)`; registers live in C locals inside it.
  - at a call the argument registers (x0-x8, v0-v7, sp) are written to `c`, and x0, x1, v0-v3 read back after.
    Nothing else crosses a call: callee-saved registers stay in the caller's locals, which is what the ABI
    promises the caller anyway.
  - image addresses are compile-time constants (the images are mapped at fixed bases).
  - calls through the import table are bound at translation time: to another translated function, or to a
    host function H_<name> written in C.
"""
import re, struct, sys, collections
from capstone import Cs, CS_ARCH_ARM64, CS_MODE_ARM

U64 = 0xFFFFFFFFFFFFFFFF


class Elf:
    def __init__(self, path, index, base):
        self.path, self.index, self.base = path, index, base
        self.d = d = open(path, "rb").read()
        phoff, = struct.unpack_from("<Q", d, 0x20)
        pes, pn = struct.unpack_from("<HH", d, 0x36)
        self.ph = [struct.unpack_from("<IIQQQQQQ", d, phoff + i * pes) for i in range(pn)]
        shoff, = struct.unpack_from("<Q", d, 0x28)
        es, n, sx = struct.unpack_from("<HHH", d, 0x3A)
        sh = [struct.unpack_from("<IIQQQQIIQQ", d, shoff + i * es) for i in range(n)]
        stro = sh[sx][4]
        self.sec = {d[stro + x[0]:d.index(b"\0", stro + x[0])].decode(): x for x in sh}
        dyn, ds = self.sec[".dynsym"], self.sec[".dynstr"]
        self.syms = []          # (name, value, size, shndx, type)
        for i in range(dyn[5] // 24):
            nm, info, oth, ndx, val, size = struct.unpack_from("<IBBHQQ", d, dyn[4] + i * 24)
            self.syms.append((d[ds[4] + nm:d.index(b"\0", ds[4] + nm)].decode(), val, size, ndx, info & 15))
        self.exports = {s[0]: s[1] for s in self.syms if s[3] and s[0]}
        self.byaddr = {}
        for s in self.syms:
            if s[3] and s[4] == 2:
                self.byaddr.setdefault(s[1], s[0])
        self.pltgot = {}        # got slot address -> symbol name
        if ".rela.plt" in self.sec:
            rp = self.sec[".rela.plt"]
            for i in range(rp[5] // 24):
                off, info, add = struct.unpack_from("<QQq", d, rp[4] + i * 24)
                self.pltgot[off] = self.syms[info >> 32][0]
        p = self.sec.get(".plt")
        self.plt = (p[3], p[3] + p[5]) if p else (0, 0)
        t = self.sec[".text"]
        self.text = (t[3], t[3] + t[5])
        self.md = Cs(CS_ARCH_ARM64, CS_MODE_ARM)
        self.funcs = self._functions()
        self.starts = sorted(self.funcs)
        self.relmap = {}        # data slot -> image address stored there by a relocation
        rd = self.sec.get(".rela.dyn")
        if rd:
            for i in range(rd[5] // 24):
                off, info, add = struct.unpack_from("<QQq", d, rd[4] + i * 24)
                t = info & 0xFFFFFFFF
                if t == 1027:
                    self.relmap[off] = add & U64
                elif t in (257, 1025):
                    sym = self.syms[info >> 32]
                    if sym[3]:
                        self.relmap[off] = (sym[1] + (add if t == 257 else 0)) & U64
        self.objects = sorted((s[1], s[2]) for s in self.syms if s[3] and s[4] == 1 and s[2])
        self.relslots = sorted(self.relmap)

    def code_pointers(self, addr):
        """Function addresses reachable from the data at addr: the whole object if a symbol covers it (a vtable,
        a table of handlers), else the run of pointer slots starting there."""
        import bisect
        out = []
        i = bisect.bisect_right(self.objects, (addr, 1 << 62)) - 1
        if i >= 0 and self.objects[i][0] <= addr < self.objects[i][0] + self.objects[i][1]:
            lo, hi = self.objects[i][0], self.objects[i][0] + self.objects[i][1]
            j = bisect.bisect_left(self.relslots, lo)
            while j < len(self.relslots) and self.relslots[j] < hi:
                t = self.relmap[self.relslots[j]]
                if t in self.funcs:
                    out.append(t)
                j += 1
            return out
        a = addr
        for _ in range(64):
            t = self.relmap.get(a)
            if t is None or t not in self.funcs:
                break
            out.append(t)
            a += 8
        return out

    def off(self, va):
        for t, fl, o, v, pa, fs, ms, al in self.ph:
            if t == 1 and v <= va < v + fs:
                return o + va - v
        return None

    def read(self, va, n):
        o = self.off(va)
        return self.d[o:o + n]

    def _functions(self):
        """{start: size} from .eh_frame FDEs and the dynamic symbols."""
        f = {}
        for s in self.syms:
            if s[3] and s[4] == 2 and s[2] and self.text[0] <= s[1] < self.text[1]:
                f[s[1]] = max(f.get(s[1], 0), s[2])
        sec = self.sec.get(".eh_frame")
        if sec:
            d, off, va, end = self.d, sec[4], sec[3], sec[4] + sec[5]
            cies, p = {}, off

            def uleb(q):
                v = sh = 0
                while True:
                    b = d[q]; q += 1
                    v |= (b & 0x7F) << sh; sh += 7
                    if not b & 0x80:
                        return v, q

            def enc_read(q, enc):
                fmt = {0: "<Q", 2: "<H", 3: "<I", 4: "<Q", 0xA: "<h", 0xB: "<i", 0xC: "<q"}[enc & 0xF]
                v, = struct.unpack_from(fmt, d, q)
                if (enc & 0x70) == 0x10:
                    v += va + (q - off)
                return v & U64, q + struct.calcsize(fmt)

            while p + 4 <= end:
                length, = struct.unpack_from("<I", d, p)
                if length == 0:
                    break
                start = p + 4
                cid, = struct.unpack_from("<I", d, start)
                if cid == 0:
                    q = start + 5
                    e = d.index(b"\0", q); aug = d[q:e].decode(); q = e + 1
                    _, q = uleb(q); _, q = uleb(q)          # alignment factors (sleb read as uleb: same length)
                    if d[start + 4] == 1:
                        q += 1
                    else:
                        _, q = uleb(q)
                    fde_enc = 0
                    if aug.startswith("z"):
                        _, q = uleb(q)
                        for ch in aug[1:]:
                            if ch == "R":
                                fde_enc = d[q]; q += 1
                            elif ch == "P":
                                pe = d[q]; q += 1
                                _, q = enc_read(q, pe)
                            elif ch == "L":
                                q += 1
                    cies[p] = fde_enc
                else:
                    enc = cies.get(start - cid, 0x1B)
                    begin, q = enc_read(start + 4, enc)
                    size, q = enc_read(q, enc & 0xF)
                    if size and self.text[0] <= begin < self.text[1]:
                        f[begin] = max(f.get(begin, 0), size)
                p = start + length
        return f

    def plt_target(self, va):
        """The symbol a PLT stub jumps to, or None."""
        ins = list(self.md.disasm(self.read(va, 16), va))
        if len(ins) >= 2 and ins[0].mnemonic == "adrp" and ins[1].mnemonic == "ldr":
            page = int(ins[0].op_str.split("#")[1], 0)
            m = re.search(r"#(0x[0-9a-f]+|\d+)\]", ins[1].op_str)
            return self.pltgot.get(page + (int(m.group(1), 0) if m else 0))
        return None


